-- 검사: 문항 세트마다 평정요소 배점 합 = 100
do $$
declare r record;
begin
  for r in
    select question_set, sum(factor_points) as total
    from (select distinct question_set, factor, factor_points from questions where cycle_id = 1) f
    group by question_set
  loop
    if r.total <> 100 then
      raise exception '문항 세트 % 배점 합이 % 입니다 (100이어야 함)', r.question_set, r.total;
    end if;
  end loop;
end
$$;
